-- Paediatric growth: the reference tables (CP47, [R-06], D-21).
--
-- A named hard requirement, and the checkpoint most exposed to a clinical decision that is
-- not engineering's to make. **D-21 was resolved at CP14**: WHO Growth Standards below 5.0
-- years, CDC 2000 from 5.0 years to 20. The reasoning is in the plan; what matters here is
-- that the decision is **data**, not code — the band table below says which standard applies
-- to which age, and Dr. Nahid can change it without a migration, which is what D-21 promised.
--
-- # Where the numbers come from
--
-- The **published L, M and S parameters**, unmodified:
--
--   * WHO Child Growth Standards (2006), 0–60 months: length/height-for-age,
--     weight-for-age, BMI-for-age, boys and girls.
--   * CDC 2000 Growth Charts (National Center for Health Statistics), from 60 months:
--     stature-for-age, weight-for-age, BMI-for-age, boys and girls.
--
-- Both are published for clinical use; CDC 2000 is a work of the United States government.
-- Neither has been re-fitted, smoothed or interpolated on the way in. `tools/growth/` holds
-- the script that produced this file from the published tables, so the derivation is
-- reproducible rather than a claim.
--
-- # How they are verified
--
-- Both sources publish, beside their L/M/S, the **percentile or SD cut-offs those parameters
-- produce**. Every one of those — 1,452 age points, roughly twelve thousand printed values —
-- is in `packages/clinical-calc/fixtures/growth-reference.json`, and CP47's test recomputes
-- each from the rows below. That is a validation set nobody in this project wrote: it is
-- WHO's and CDC's own arithmetic, and it fails if a single parameter was transcribed wrongly.
--
-- # The 5.0-year switch is real and must stay visible
--
-- A percentile computed under WHO and one computed under CDC are not the same measurement.
-- D-21 is explicit: the chart shows where the reference changes, and the two are never
-- compared numerically. Every stored percentile therefore carries the standard **and its
-- version**, so a value from 2026 stays interpretable if the protocol moves.

-- +goose Up

CREATE TABLE core.growth_standard (
  code text PRIMARY KEY,
  -- Bumped when the reference data changes, never when a comment does. Stored with every
  -- computed percentile, so a value remains interpretable against the table that produced it.
  version text NOT NULL,
  name_en text NOT NULL,
  name_bn text NOT NULL,
  -- The citation, for whoever asks where a number came from. Not decoration: a percentile
  -- with no provenance is a number a clinician cannot defend to a parent.
  source text NOT NULL,
  min_age_months numeric(7,4) NOT NULL,
  max_age_months numeric(7,4) NOT NULL,
  CONSTRAINT growth_standard_age_band_is_ordered CHECK (min_age_months < max_age_months)
);

-- The indicators. Three, deliberately: head circumference and the rest of the WHO set are not
-- here because this clinic does not measure them, and a table of curves nobody plots is a
-- table that goes stale without anybody noticing.
CREATE TABLE core.growth_lms (
  standard_code text NOT NULL REFERENCES core.growth_standard(code),
  -- HFA height-for-age, WFA weight-for-age, BFA BMI-for-age.
  indicator text NOT NULL CHECK (indicator IN ('HFA', 'WFA', 'BFA')),
  sex text NOT NULL CHECK (sex IN ('male', 'female')),
  -- Age in months, as the published tables key them. WHO's are whole months; CDC's fall on
  -- half-months, which is not a rounding artefact — it is how CDC publishes them.
  age_months numeric(7,4) NOT NULL,

  -- The Box-Cox parameters. z = ((X/M)^L - 1) / (L*S), or ln(X/M)/S when L is zero.
  l numeric NOT NULL,
  m numeric NOT NULL CHECK (m > 0),
  s numeric NOT NULL CHECK (s > 0),

  PRIMARY KEY (standard_code, indicator, sex, age_months)
);

-- Which standard applies to which age, per indicator. **This is D-21, as data.**
--
-- Changing the protocol is an UPDATE here and a recomputation over stored measurements — not
-- a migration, and not a code release. That was the explicit promise the decision was
-- recorded under, and it is only true if this table exists.
CREATE TABLE core.growth_band (
  indicator text NOT NULL CHECK (indicator IN ('HFA', 'WFA', 'BFA')),
  min_age_months numeric(7,4) NOT NULL,
  max_age_months numeric(7,4) NOT NULL,
  standard_code text NOT NULL REFERENCES core.growth_standard(code),
  PRIMARY KEY (indicator, min_age_months),
  CONSTRAINT growth_band_is_ordered CHECK (min_age_months < max_age_months)
);

