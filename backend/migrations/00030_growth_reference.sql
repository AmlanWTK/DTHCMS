-- The LMS parameters reproduce the cut-offs their own publishers printed.
--
-- Not asserted here — that is CP47's test, which reads the published columns from
-- `packages/clinical-calc/fixtures/growth-reference.json` and recomputes all twelve thousand
-- of them. What *is* asserted here is the structural half a test cannot see from outside: a
-- band that names an age no table covers.
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION core.assert_every_growth_band_has_a_table_behind_it() RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  offender record;
BEGIN
  -- A band whose standard does not cover its own age range.
  SELECT b.indicator, b.min_age_months, b.max_age_months, b.standard_code
    INTO offender
    FROM core.growth_band b
    JOIN core.growth_standard s ON s.code = b.standard_code
   WHERE b.min_age_months < s.min_age_months OR b.max_age_months > s.max_age_months
   LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION '% band %..% names %, which does not cover it',
      offender.indicator, offender.min_age_months, offender.max_age_months, offender.standard_code;
  END IF;

  -- A band whose table does not reach within a month of the band's own edges.
  --
  -- One month is the engine's edge tolerance, and it exists for one real gap: WHO's last
  -- published row is at 60.0 months and CDC's first is at 60.5, so a child in that fortnight
  -- is inside the CDC band and outside the CDC table. Anything wider than that is a hole in
  -- the reference data, and a hole is what makes a percentile silently disappear.
  SELECT b.indicator, b.standard_code, b.min_age_months INTO offender
    FROM core.growth_band b
   WHERE (SELECT min(l.age_months) FROM core.growth_lms l
           WHERE l.standard_code = b.standard_code AND l.indicator = b.indicator)
         > b.min_age_months + 1
      OR (SELECT max(l.age_months) FROM core.growth_lms l
           WHERE l.standard_code = b.standard_code AND l.indicator = b.indicator)
         < b.max_age_months - 1
   LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'the % band from % months is not covered by %''s own table',
      offender.indicator, offender.min_age_months, offender.standard_code
      USING HINT = 'A child whose age falls in the uncovered part gets no percentile at '
                   'all, silently.';
  END IF;

  -- A band with no rows at all for one of the sexes. The failure this prevents is a girl
  -- getting "not applicable" at an age where a boy gets a percentile.
  SELECT b.indicator, b.standard_code, x.sex
    INTO offender
    FROM core.growth_band b
    CROSS JOIN (VALUES ('male'), ('female')) AS x(sex)
   WHERE NOT EXISTS (
     SELECT 1 FROM core.growth_lms l
      WHERE l.standard_code = b.standard_code
        AND l.indicator = b.indicator
        AND l.sex = x.sex
        AND l.age_months >= b.min_age_months
        AND l.age_months <= b.max_age_months)
   LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'no % rows for % under %',
      offender.indicator, offender.sex, offender.standard_code;
  END IF;

  -- A gap between bands. A child of exactly 60.0 months must land somewhere.
  SELECT b.indicator, b.max_age_months INTO offender
    FROM core.growth_band b
   WHERE b.max_age_months < (SELECT max(max_age_months) FROM core.growth_band b2
                              WHERE b2.indicator = b.indicator)
     AND NOT EXISTS (SELECT 1 FROM core.growth_band n
                      WHERE n.indicator = b.indicator
                        AND n.min_age_months = b.max_age_months)
   LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'the % bands have a gap at % months', offender.indicator, offender.max_age_months
      USING HINT = 'A child whose age falls in the gap would get no percentile at all, '
                   'silently, which is worse than getting the wrong one.';
  END IF;
END;
$$;
-- +goose StatementEnd

-- The parameters must be usable. An L, M or S that produces a non-finite z-score for an
-- ordinary measurement is a transcription error that a spot check would miss.
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION core.assert_growth_parameters_are_usable() RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  offender record;
BEGIN
  SELECT standard_code, indicator, sex, age_months INTO offender
    FROM core.growth_lms
   WHERE m <= 0 OR s <= 0 OR s > 1 OR abs(l) > 10
   LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION '% % % at % months has parameters no measurement can be scored against',
      offender.standard_code, offender.indicator, offender.sex, offender.age_months;
  END IF;
END;
$$;
-- +goose StatementEnd

