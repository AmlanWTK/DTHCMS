// TestAPromptEditedUnderTheSameVersionIsRefused.
//
// The single change that would make every stored interaction unreproducible: the record names a
// version whose text no longer exists anywhere. A process that will not start is a bad morning; a
// clinical audit trail that quietly stopped meaning anything is a worse year.
func TestAPromptEditedUnderTheSameVersionIsRefused(t *testing.T) {
	h := newHarness(t)
	ctx := context.Background()

	// Deploying the same build twice is start-up succeeding.
	if err := h.registry.Deploy(ctx, h.store, h.clock.Now()); err != nil {
		t.Fatalf("re-deploying an unchanged build failed: %v", err)
	}

	// Now the same version with different text, which is what an edit-without-a-bump looks like
	// from the database's side.
	if _, err := h.SQL.Exec(
		`UPDATE core.ai_prompt_version SET content_sha256 = repeat('b', 64) WHERE version = '1.0.0'`); err != nil {
		t.Fatal(err)
	}
	err := h.registry.Deploy(ctx, h.store, h.clock.Now())
	if err == nil {
		t.Fatal("a prompt edited under an unchanged version number was accepted")
	}
	if !strings.Contains(err.Error(), "Bump the version") {
		t.Errorf("the refusal does not say what to do instead: %v", err)
	}
}

// TestTheRegistryIsMirroredInTheDatabase.
func TestTheRegistryIsMirroredInTheDatabase(t *testing.T) {
	h := newHarness(t)
	deployed, err := h.store.DeployedPrompts(context.Background(), true)
	if err != nil {
		t.Fatal(err)
	}
	stored := map[string]string{}
	for _, p := range deployed {
		stored[p.AgentCode+"@"+p.Version] = p.ContentSHA256
		if p.Content == "" {
			t.Errorf("%s %s stored no content; a hash says a prompt changed and not what it said",
				p.AgentCode, p.Version)
		}
	}
	for _, p := range h.registry.All() {
		key := p.AgentCode + "@" + p.Version
		got, ok := stored[key]
		if !ok {
			t.Errorf("%s is in the build and not in the database", key)
			continue
		}
		if got != p.SHA256 {
			t.Errorf("%s hashes to %s in the build and %s in the database", key, p.SHA256, got)
		}
		delete(stored, key)
	}
	for key := range stored {
		t.Errorf("%s is in the database and not in the build", key)
	}
}

