// The AI gateway against a real database (CP70).
//
// Everything here needs one, and the reason is worth stating rather than assuming: the two rules
// this checkpoint exists for are enforced by the database as well as by Go — the tier guard by a
// check constraint and invariant 99, the identifier rule by `ops.carries_identifier` and invariant
// 98 — and a test that stubbed the store would prove the Go half and quietly assert nothing about
// the half that is meant to catch the Go half being wrong.

type harness struct {
	*testsupport.DB
	pool     *pgxpool.Pool
	store    *ai.Store
	registry *ai.Registry
	clock    *clock.Fixed
	logger   *slog.Logger

	facility uuid.UUID
	// realPatient is a patient row nobody has entered in the synthetic register. Everything about
	// it is therefore, by default, unsendable on a free credential — which is the property
	// criterion 1b is about.
	realPatient uuid.UUID
	// fabricated is a subject that *has* been registered, with a reason, as CP13's generator would
	// register one.
	fabricated uuid.UUID

	provider *ai.Mock
	// raised is every budget alert the gateway put in front of an administrator, in order. The
	// table's unique key makes a crossing recorded once; this is the *other* half of criterion 5 —
	// that somebody is told once, rather than on every call for the rest of the day.
	raised []ai.BudgetAlert
}

// RaiseBudgetAlert makes the harness itself the AlertRaiser, standing in for the administrators'
// console that audit's store provides at the composition root.
func (h *harness) RaiseBudgetAlert(_ context.Context, alert ai.BudgetAlert) error {
	h.raised = append(h.raised, alert)
	return nil
}

func newHarness(t *testing.T) *harness {
	t.Helper()
	base := testsupport.Postgres(t)
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	t.Cleanup(cancel)

	pool, err := pgxpool.New(ctx, base.DSN)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)

	registry, err := ai.LoadRegistry()
	if err != nil {
		t.Fatal(err)
	}

	h := &harness{
		DB: base, pool: pool, store: ai.NewStore(pool), registry: registry,
		// Ten in the morning in Faridpur, which is 04:00 UTC. The hour matters to the metering
		// tests: a clock set near midnight UTC would put two calls of one test on either side of
		// the day boundary and the budget arithmetic would be right and the test wrong.
		clock:       clock.NewFixed(time.Date(2026, 9, 14, 4, 0, 0, 0, time.UTC)),
		logger:      slog.New(slog.NewTextHandler(io.Discard, nil)),
		realPatient: uuid.New(),
		fabricated:  uuid.New(),
		provider:    ai.NewMock(),
	}
	if err := base.SQL.QueryRow(`SELECT core.default_facility()`).Scan(&h.facility); err != nil {
		t.Fatal(err)
	}
	if _, err := base.SQL.Exec(`
		INSERT INTO core.patient (id, facility_id, clinical_id, name_en, name_bn, sex, birth_date,
		                          dob_precision, dob_verified_by, phone_primary, status, registered_at)
		VALUES ($1, $2, 'DTHC-FRD-2026-000701', 'Ayesha Rahman', 'আয়েশা রহমান', 'female',
		        DATE '1984-03-11', 'day', 'national_id', '+8801711234567', 'active', now())`,
		h.realPatient, h.facility); err != nil {
		t.Fatal(err)
	}

	if err := registry.Deploy(ctx, h.store, h.clock.Now()); err != nil {
		t.Fatalf("deploying the prompt registry: %v", err)
	}
	return h
}

// registerFabricated does what cmd/synthload will do: enters a subject in the register, with the
// reason the constraint insists on.
func (h *harness) registerFabricated(t *testing.T, subject uuid.UUID) {
	t.Helper()
	if err := h.store.RegisterSynthetic(context.Background(), subject, h.facility,
		"generated by the synthetic caseload loader for development and evaluation", nil,
		h.clock.Now()); err != nil {
		t.Fatal(err)
	}
}

// gateway builds one on this harness's store, at the given tier and environment.
func (h *harness) gateway(t *testing.T, tier config.AITier, env config.Environment) *ai.Gateway {
	t.Helper()
	m, err := ai.NewMinimiser(testPepper)
	if err != nil {
		t.Fatal(err)
	}
	return ai.NewGateway(ai.GatewayConfig{
		Store: h.store, Registry: h.registry, Provider: h.provider, Minimiser: m,
		Breaker: ai.NewBreaker(3, 30*time.Second, h.clock.Now),
		Tier:    tier, Env: env, Facility: h.facility,
		Alerts: h, Clock: h.clock, Logger: h.logger,
		// No jitter, so a retry test's timing is the policy's rather than the dice's.
		Jitter: func() float64 { return 0.5 },
	})
}

func (h *harness) request(subject uuid.UUID, payload map[string]any) ai.Request {
	return ai.Request{
		AgentCode: "gateway.echo",
		Subject: ai.Subject{
			PatientID: subject, AgeMonths: 511, Sex: "female",
			Identifiers: map[string]string{
				"name_en": "Ayesha Rahman", "name_bn": "আয়েশা রহমান",
				"phone": "01711-234567", "nid": "1990123456789",
			},
		},
		Payload: payload,
	}
}

func (h *harness) rows(t *testing.T, where string, args ...any) int {
	t.Helper()
	var n int
	if err := h.SQL.QueryRow(`SELECT count(*) FROM core.ai_interaction WHERE `+where, args...).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func (h *harness) latest(t *testing.T) ai.Interaction {
	t.Helper()
	var id uuid.UUID
	if err := h.SQL.QueryRow(
		`SELECT id FROM core.ai_interaction ORDER BY started_at DESC, ctid DESC LIMIT 1`).Scan(&id); err != nil {
		t.Fatalf("no interaction was recorded at all: %v", err)
	}
	interaction, err := h.store.Interaction(context.Background(), h.facility, id)
	if err != nil {
		t.Fatal(err)
	}
	return interaction
}

// verifyInvariants runs the database's own checks, which is where criteria 1 and 1b are re-asserted
// over the whole table rather than row by row.
func (h *harness) verifyInvariants(t *testing.T) {
	t.Helper()
	rows, err := h.SQL.Query(`SELECT function_name FROM ops.invariant WHERE sequence BETWEEN 98 AND 102`)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = rows.Close() }()
	var names []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			t.Fatal(err)
		}
		names = append(names, name)
	}
	if len(names) != 5 {
		t.Fatalf("expected the five CP70 invariants to be registered, found %d: %v", len(names), names)
	}
	for _, name := range names {
		if _, err := h.SQL.Exec(`SELECT core.` + name + `()`); err != nil {
			t.Errorf("invariant %s failed: %v", name, err)
		}
	}
}

// --- criterion 1b: a real-patient payload cannot go out on a free credential ---

// TestARealPatientPayloadCannotBeSentOnAFreeTierCredential is the checkpoint's sharpest criterion.
//
// Note what the test does *not* do: it never tells the gateway that this patient is real. There is
// nowhere to say it. The patient exists, nobody entered them in the synthetic register, and that is
// the whole of the decision — which is the point, because a caller that had to declare it would one
// day forget.
func TestARealPatientPayloadCannotBeSentOnAFreeTierCredential(t *testing.T) {
	h := newHarness(t)
	var called int
	h.provider.Respond = func(ai.ProviderRequest) (ai.ProviderResponse, error) {
		called++
		return ai.ProviderResponse{}, nil
	}

	_, err := h.gateway(t, config.TierFree, config.EnvDev).Invoke(context.Background(),
		h.request(h.realPatient, map[string]any{"note": "routine review"}))

	if !errors.Is(err, ai.ErrFreeTierRefused) {
		t.Fatalf("the call was not refused: %v", err)
	}
	if called != 0 {
		t.Errorf("the provider was contacted %d times; the guard must fail closed, not after the fact", called)
	}

	// And the refusal is recorded, because a refused call is exactly the one somebody asks about.
	row := h.latest(t)
	if row.Status != "REFUSED_TIER" {
		t.Errorf("status = %q, want REFUSED_TIER", row.Status)
	}
	if row.Provenance != string(ai.ProvenanceRealPatient) {
		t.Errorf("provenance = %q, want REAL_PATIENT", row.Provenance)
	}
	if row.Tier != "free" {
		t.Errorf("tier = %q, want free", row.Tier)
	}
	if !strings.Contains(row.RefusalDetail, "free tier") {
		t.Errorf("the refusal does not say what it objected to: %q", row.RefusalDetail)
	}
	if len(row.Outbound) != 0 {
		t.Error("the payload of a call we decided not to make was kept anyway")
	}
	h.verifyInvariants(t)
}

// TestASubjectNobodyRegisteredIsTreatedAsReal.
//
// The default-deny half. This subject is not in the patient table either — it is a bare uuid, the
// shape a records-extraction job would pass for a document nobody has filed yet — and it is still
// refused, because "we have never heard of this" is not evidence of anything.
func TestASubjectNobodyRegisteredIsTreatedAsReal(t *testing.T) {
	h := newHarness(t)
	_, err := h.gateway(t, config.TierFree, config.EnvDev).Invoke(context.Background(),
		h.request(uuid.New(), map[string]any{"note": "routine"}))
	if !errors.Is(err, ai.ErrFreeTierRefused) {
		t.Fatalf("an unregistered subject was allowed onto the free tier: %v", err)
	}
	if h.latest(t).Provenance != string(ai.ProvenanceRealPatient) {
		t.Error("an unregistered subject was not recorded as a real patient")
	}
}

// TestAPayloadWithNoSubjectAtAllIsTreatedAsReal. An unlinked scanned report is a real patient's
// report; it has just not been filed yet.
func TestAPayloadWithNoSubjectAtAllIsTreatedAsReal(t *testing.T) {
	h := newHarness(t)
	_, err := h.gateway(t, config.TierFree, config.EnvDev).Invoke(context.Background(),
		h.request(uuid.Nil, map[string]any{"note": "routine"}))
	if !errors.Is(err, ai.ErrFreeTierRefused) {
		t.Fatalf("a subjectless payload was allowed onto the free tier: %v", err)
	}
	if got := h.latest(t).Provenance; got != string(ai.ProvenanceUnknown) {
		t.Errorf("provenance = %q, want UNKNOWN — 'we could not tell' and 'we checked and it is real' are different facts", got)
	}
}

// TestAFabricatedSubjectMayUseTheFreeTier is the other side, and without it the guard could be
// "refuse everything" and pass every test above.
func TestAFabricatedSubjectMayUseTheFreeTier(t *testing.T) {
	h := newHarness(t)
	h.registerFabricated(t, h.fabricated)

	result, err := h.gateway(t, config.TierFree, config.EnvDev).Invoke(context.Background(),
		h.request(h.fabricated, map[string]any{"note": "routine"}))
	if err != nil {
		t.Fatalf("a registered synthetic subject was refused: %v", err)
	}
	if !result.AIGenerated {
		t.Error("the result is not marked ai_generated")
	}
	row := h.latest(t)
	if row.Status != "SUCCEEDED" || row.Provenance != string(ai.ProvenanceSynthetic) {
		t.Errorf("row = %s/%s, want SUCCEEDED/SYNTHETIC", row.Status, row.Provenance)
	}
	h.verifyInvariants(t)
}

// TestTheFreeTierIsRefusedOutsideDevelopmentEvenForAFabricatedSubject.
//
// The second, independent condition. The register decides whether *this payload* is fabricated; the
// environment decides whether the deployment is one where that question can be trusted at all. A
// staging system restored from a production backup is one bad INSERT away from having real patients
// registered, and this is what makes that insufficient rather than fatal.
func TestTheFreeTierIsRefusedOutsideDevelopmentEvenForAFabricatedSubject(t *testing.T) {
	h := newHarness(t)
	h.registerFabricated(t, h.fabricated)

	for _, env := range []config.Environment{config.EnvStaging, config.EnvProduction} {
		t.Run(string(env), func(t *testing.T) {
			_, err := h.gateway(t, config.TierFree, env).Invoke(context.Background(),
				h.request(h.fabricated, map[string]any{"note": "routine"}))
			if !errors.Is(err, ai.ErrFreeTierRefused) {
				t.Fatalf("the free tier was usable in %s: %v", env, err)
			}
			if !strings.Contains(h.latest(t).RefusalDetail, string(env)) {
				t.Error("the refusal does not name the environment it objected to")
			}
		})
	}
}

