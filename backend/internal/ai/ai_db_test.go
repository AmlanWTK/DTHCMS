// --- the circuit breaker and the fallback, end to end ---

func TestAnOpenCircuitIsRecordedRatherThanRetriedForever(t *testing.T) {
	h := newHarness(t)
	h.provider.Respond = func(ai.ProviderRequest) (ai.ProviderResponse, error) {
		return ai.ProviderResponse{}, fmt.Errorf("%w: down", ai.ErrProviderUnavailable)
	}
	gateway := h.gateway(t, config.TierPaid, config.EnvProduction)
	ctx := context.Background()

	// gateway.echo allows three attempts, so the first invocation alone trips a three-failure
	// breaker. The second invocation must not reach the provider at all.
	if _, err := gateway.Invoke(ctx, h.request(h.realPatient, map[string]any{"n": 1})); err == nil {
		t.Fatal("a provider outage was reported as success")
	}
	var calls int
	h.provider.Respond = func(ai.ProviderRequest) (ai.ProviderResponse, error) {
		calls++
		return ai.ProviderResponse{}, fmt.Errorf("%w: down", ai.ErrProviderUnavailable)
	}
	if _, err := gateway.Invoke(ctx, h.request(h.realPatient, map[string]any{"n": 2})); err == nil {
		t.Fatal("the second call was reported as success")
	}
	if calls != 0 {
		t.Errorf("the provider was contacted %d times through an open circuit", calls)
	}
	if row := h.latest(t); row.Status != "CIRCUIT_OPEN" {
		t.Errorf("status = %q, want CIRCUIT_OPEN — the fast failure is what lets D-15's degraded "+
			"mode appear before the consultation rather than five minutes into it", row.Status)
	}
}
