// TestABudgetAlertFiresAtEachThresholdOnceADay.
//
// Two properties, and the second is the one that decides whether anybody still reads the alerts in
// six months: every configured threshold fires, and each fires **once**. An alert that fired on
// every call for the rest of the day is one somebody turns off, which is how a clinic ends up with
// no alerting at all on the day it matters.
func TestABudgetAlertFiresAtEachThresholdOnceADay(t *testing.T) {
	h := newHarness(t)
	// A budget small enough that one call crosses 60% and two cross 100%. The seeded ten dollars a
	// day is a proposal for production, not a figure a test should depend on.
	if _, err := h.SQL.Exec(
		`UPDATE core.ai_budget SET daily_micro_usd = 4000000 WHERE facility_id = $1 AND agent_code IS NULL`,
		h.facility); err != nil {
		t.Fatal(err)
	}

	h.provider.Respond = func(ai.ProviderRequest) (ai.ProviderResponse, error) {
		// 2.8 US dollars a call, against a four-dollar budget: 70% after one, 140% after two.
		return ai.ProviderResponse{
			Text: `{"summary":"ok","field_count":1}`, ModelVersion: ai.MockModelVersion,
			InputTokens: 1_000_000, OutputTokens: 1_000_000,
		}, nil
	}
	gateway := h.gateway(t, config.TierPaid, config.EnvProduction)
	ctx := context.Background()

	if _, err := gateway.Invoke(ctx, h.request(h.realPatient, map[string]any{"n": 1})); err != nil {
		t.Fatal(err)
	}
	alerts, err := h.store.BudgetAlerts(ctx, h.facility, h.clock.Now().AddDate(0, 0, -1), 50)
	if err != nil {
		t.Fatal(err)
	}
	if len(alerts) != 1 || alerts[0].ThresholdPercent != 60 {
		t.Fatalf("after one call the alerts are %v; want exactly the 60%% one", alerts)
	}
	if len(h.raised) != 1 {
		t.Fatalf("%d alerts reached the administrators' console, want 1", len(h.raised))
	}

	if _, err := gateway.Invoke(ctx, h.request(h.realPatient, map[string]any{"n": 2})); err != nil {
		t.Fatal(err)
	}
	alerts, err = h.store.BudgetAlerts(ctx, h.facility, h.clock.Now().AddDate(0, 0, -1), 50)
	if err != nil {
		t.Fatal(err)
	}
	crossed := map[int]int{}
	for _, alert := range alerts {
		crossed[alert.ThresholdPercent]++
	}
	if crossed[60] != 1 || crossed[80] != 1 || crossed[100] != 1 {
		t.Errorf("thresholds crossed = %v; want each of 60, 80 and 100 exactly once", crossed)
	}

	// A third call crosses nothing new, and this is the assertion that matters most.
	if _, err := gateway.Invoke(ctx, h.request(h.realPatient, map[string]any{"n": 3})); err != nil {
		t.Fatal(err)
	}
	alerts, err = h.store.BudgetAlerts(ctx, h.facility, h.clock.Now().AddDate(0, 0, -1), 50)
	if err != nil {
		t.Fatal(err)
	}
	if len(alerts) != 3 {
		t.Errorf("%d alerts after three calls; each threshold must fire once a day, not once a call", len(alerts))
	}

	// And the console, which is the half a table-only assertion misses. The `ON CONFLICT DO
	// NOTHING` keeps the *record* to one row per threshold per day whatever the Go code does; what
	// this checks is that nobody is *told* twice. An alert that arrives on every call for the rest
	// of the day is one somebody turns off, and then there is no alerting at all on the day it
	// matters.
	told := map[int]int{}
	for _, alert := range h.raised {
		told[alert.ThresholdPercent]++
		if alert.SpendMicroUSD == 0 || alert.BudgetMicroUSD == 0 {
			t.Errorf("an alert reached the console with no figures on it: %+v", alert)
		}
	}
	if len(h.raised) != 3 || told[60] != 1 || told[80] != 1 || told[100] != 1 {
		t.Errorf("the administrators were told %v (%d alerts in total); want each threshold exactly once",
			told, len(h.raised))
	}
}

