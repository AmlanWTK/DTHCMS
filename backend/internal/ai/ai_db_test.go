// TestThePayloadCheckAgreesWithTheDatabase.
//
// The Go minimiser refuses first so the message names the key; the constraint is the backstop. A
// backstop narrower than the thing it backs is not one — and one *wider* than it means a payload
// that passes Go arrives as an opaque constraint violation. Both directions matter, so both are
// checked, over payloads shaped like the ones an agent will actually build.
func TestThePayloadCheckAgreesWithTheDatabase(t *testing.T) {
	h := newHarness(t)
	ctx := context.Background()
	m, err := ai.NewMinimiser(testPepper)
	if err != nil {
		t.Fatal(err)
	}

	payloads := map[string]map[string]any{
		"a bare identifier key":     {"phone": "01711234567"},
		"a suffixed identifier key": {"guardian_phone": "01711234567"},
		"a doubly suffixed one":     {"mother_name_bn": "আয়েশা"},
		"one buried two levels in":  {"visit": map[string]any{"patient": map[string]any{"nid": "1990123456789"}}},
		"one inside an array":       {"visits": []any{map[string]any{"address": "House 12"}}},
		"a credential":              {"token": "eyJhbGciOi"},
		"a clinical key, permitted": {"diagnosis": "type 2 diabetes mellitus"},
		"clean structured data":     {"hba1c": 8.2, "unit": "%"},
		"a free-text number":        {"note": "call 01711-234567 tomorrow"},
		"clean prose":               {"note": "BP 120/80, adherence good"},
	}

	for name, payload := range payloads {
		t.Run(name, func(t *testing.T) {
			_, goErr := m.Minimise("gateway.echo", ai.Subject{PatientID: uuid.New()}, payload)
			goRefuses := goErr != nil

			encoded, err := json.Marshal(payload)
			if err != nil {
				t.Fatal(err)
			}
			dbRefuses, err := h.store.PayloadCarriesIdentifier(ctx, encoded)
			if err != nil {
				t.Fatal(err)
			}

			// The one legitimate asymmetry: Go *scrubs* free text rather than refusing it, so a
			// note containing a phone number is refused by the raw database check and accepted by
			// Go — because by the time Go is finished the number is gone. What must agree is the
			// verdict on the payload Go actually produces.
			if goRefuses != dbRefuses {
				if minimised, err := m.Minimise("gateway.echo", ai.Subject{PatientID: uuid.New()}, payload); err == nil {
					after, err := json.Marshal(minimised.Payload)
					if err != nil {
						t.Fatal(err)
					}
					stillBad, err := h.store.PayloadCarriesIdentifier(ctx, after)
					if err != nil {
						t.Fatal(err)
					}
					if stillBad {
						t.Fatalf("Go accepted a payload the database still refuses after minimisation:\n%s", after)
					}
					return
				}
				t.Fatalf("Go refuses = %v, the database refuses = %v", goRefuses, dbRefuses)
			}
		})
	}
}

// TestTheScrubberAgreesWithTheDatabase holds the two copies of the pattern list together.
//
// Both directions on the list itself, and then — the part that actually earns the test — the same
// fixture corpus through both engines. Two regular-expression implementations agreeing about a list
// of patterns is not something to assume: PostgreSQL's ARE and Go's RE2 are different engines, and
// the whole design of patterns.go is that the expressions live in the intersection of the two.
func TestTheScrubberAgreesWithTheDatabase(t *testing.T) {
	h := newHarness(t)
	ctx := context.Background()

	stored, err := h.store.PIIPatterns(ctx)
	if err != nil {
		t.Fatal(err)
	}
	byKind := map[string]ai.Pattern{}
	for _, p := range stored {
		byKind[p.Kind] = p
	}
	for _, p := range ai.DefaultPatterns {
		got, ok := byKind[p.Kind]
		if !ok {
			t.Fatalf("%q is in ai.DefaultPatterns and not in ops.pii_pattern", p.Kind)
		}
		if got.Expression != p.Expression {
			t.Fatalf("%q is %q in Go and %q in the database", p.Kind, p.Expression, got.Expression)
		}
		if got.Replacement != p.Replacement {
			t.Fatalf("%q replaces with %q in Go and %q in the database", p.Kind, p.Replacement, got.Replacement)
		}
		delete(byKind, p.Kind)
	}
	for kind := range byKind {
		t.Fatalf("%q is in ops.pii_pattern and not in ai.DefaultPatterns", kind)
	}

	compiled, err := ai.CompilePatterns(ai.DefaultPatterns)
	if err != nil {
		t.Fatal(err)
	}
	corpus := []string{
		"rang her son Rafiq on 01711-234567",
		"+880 1711 234567",
		"01711234567",
		"NID 1990123456789",
		"০১৭১১২৩৪৫৬৭",
		"০১৭১১-২৩৪৫৬৭",
		"ayesha.rahman@example.com",
		"Escorted by Md. Rafiqul Islam",
		"symptoms include polyuria",
		"BP 120/80, pulse 72",
		"HbA1c 8.2 on 2026-03-12, 7.6 on 2026-06-04",
		"Metformin 500 mg twice daily",
		"রক্তচাপ ১২০/৮০, ওজন ৬১.৪ কেজি",
		"12 14 16 18",
		"",
	}
	for _, candidate := range corpus {
		var goSays bool
		for _, p := range compiled {
			if p.Matches(candidate) {
				goSays = true
				break
			}
		}
		dbSays, err := h.store.TextCarriesIdentifier(ctx, candidate)
		if err != nil {
			t.Fatal(err)
		}
		if goSays != dbSays {
			t.Errorf("the engines disagree about %q: Go says %v, PostgreSQL says %v",
				candidate, goSays, dbSays)
		}
	}
}

