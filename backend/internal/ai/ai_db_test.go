// This is the one thing the adapter does that looks like policy, and it is not: only the adapter
// knows that this provider says 429 with a Retry-After and puts a refusal in `finishReason` rather
// than in a status code. Translating that into the sentinel errors is what lets the gateway have
// one retry policy rather than one per provider.
func TestTheAdapterClassifiesTheProvidersFailures(t *testing.T) {
	for name, tc := range map[string]struct {
		status    int
		headers   map[string]string
		body      string
		want      error
		retryable bool
		after     time.Duration
	}{
		"a rate limit": {
			status: http.StatusTooManyRequests, headers: map[string]string{"Retry-After": "17"},
			body: `{"error":{"code":429}}`, want: ai.ErrProviderRateLimited, retryable: true,
			after: 17 * time.Second,
		},
		"a server fault": {
			status: http.StatusInternalServerError, body: `{"error":{"code":500}}`,
			want: ai.ErrProviderUnavailable, retryable: true,
		},
		"a retired model version": {
			status: http.StatusNotFound, body: `{"error":{"code":404,"message":"model not found"}}`,
			want: ai.ErrProviderRejected, retryable: false,
		},
		"a safety refusal": {
			status: http.StatusOK,
			body:   `{"candidates":[{"finishReason":"SAFETY"}],"usageMetadata":{}}`,
			want:   ai.ErrProviderRefused, retryable: false,
		},
		"a truncated body": {
			status: http.StatusOK, body: `{"candidates":[{"content":{"parts":[{"text":"unter`,
			want: ai.ErrProviderUnavailable, retryable: true,
		},
	} {
		t.Run(name, func(t *testing.T) {
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				for k, v := range tc.headers {
					w.Header().Set(k, v)
				}
				w.Header().Set("Content-Type", "application/json")
				w.WriteHeader(tc.status)
				_, _ = io.WriteString(w, tc.body)
			}))
			defer server.Close()

			_, err := ai.NewGemini(server.URL, "k", time.Second).Generate(context.Background(),
				ai.ProviderRequest{ModelVersion: "gemini-2.5-flash-001", User: "x"})
			if !errors.Is(err, tc.want) {
				t.Fatalf("got %v, want %v", err, tc.want)
			}
			if ai.Retryable(err) != tc.retryable {
				t.Errorf("retryable = %v, want %v", ai.Retryable(err), tc.retryable)
			}
			if tc.after > 0 {
				advice, ok := ai.RetryAfter(err)
				if !ok || advice != tc.after {
					t.Errorf("Retry-After = %v (%v), want %v — answering a 429 with our own curve "+
						"instead of the provider's advice is a second 429", advice, ok, tc.after)
				}
			}
		})
	}
}

// TestASafetyRefusalIsNotRetried. Asking the same question again is the one thing guaranteed not to
// change the answer, and three attempts is three times the cost for the same silence.
func TestASafetyRefusalIsNotRetried(t *testing.T) {
	h := newHarness(t)
	var calls int
	h.provider.Respond = func(ai.ProviderRequest) (ai.ProviderResponse, error) {
		calls++
		return ai.ProviderResponse{}, fmt.Errorf("%w: finish reason SAFETY", ai.ErrProviderRefused)
	}
	if _, err := h.gateway(t, config.TierPaid, config.EnvProduction).Invoke(context.Background(),
		h.request(h.realPatient, map[string]any{"a": 1})); err == nil {
		t.Fatal("a refusal was reported as a success")
	}
	if calls != 1 {
		t.Errorf("a safety refusal was retried %d times", calls)
	}
}

