package rbac

import (
	"fmt"
	"strings"

	"github.com/google/uuid"

	"github.com/AmlanWTK/DTHCMS/backend/internal/auth"
)

// RenderMatrix produces docs/access-matrix.md: the engine's answer for every role and
// every permission, against a resource within reach, with the scope or the reason.
//
// Generated rather than written so that the document cannot disagree with the code. The
// test that compares them fails a build in which somebody edited one and not the other.
func RenderMatrix() string {
	var b strings.Builder

	b.WriteString("# Access matrix\n\n")
	b.WriteString("_Generated by `go run ./tools/accessmatrix` from `internal/rbac`. Do not edit; a test compares this file with the engine._\n\n")
	b.WriteString("Every role against every permission (CP19). A cell is the decision for a person wearing that\n")
	b.WriteString("role as their active hat, acting on a resource at their own station in their own facility —\n")
	b.WriteString("the most favourable case, so what is denied here is denied everywhere. `any`, `station` and\n")
	b.WriteString("`own` are the reach of an allow; a dash is a permission the role does not hold; a named rule\n")
	b.WriteString("is an explicit deny from blueprint §4.4, which would win even if the role held the permission.\n\n")
	b.WriteString("Read it the way the blueprint is written: one paragraph per role.\n\n")

	facility := uuid.MustParse("00000000-0000-0000-0000-000000000001")
	station := uuid.MustParse("00000000-0000-0000-0000-000000000002")
	user := uuid.MustParse("00000000-0000-0000-0000-000000000003")
	resource := Resource{Kind: "record", FacilityID: facility, StationID: &station, OwnerID: &user}

	for _, role := range auth.AllRoles {
		fmt.Fprintf(&b, "## %s\n\n", role)
		subject := Subject{
			UserID: user, FacilityID: facility, Roles: []auth.RoleCode{role}, ActiveRole: role,
			StationID: &station, Permissions: UnionFor([]auth.RoleCode{role}),
		}
		b.WriteString("| Permission | Decision |\n| --- | --- |\n")
		for _, action := range auth.AllPermissions {
			d := Can(subject, action, resource)
			var cell string
			switch {
			case d.Allowed:
				cell = "allow (" + shortScope(d.Scope) + ")"
			case d.Rule != "":
				cell = "**deny** — " + d.Rule
			default:
				cell = "—"
			}
			fmt.Fprintf(&b, "| `%s` | %s |\n", action, cell)
		}
		b.WriteString("\n")
	}

	b.WriteString("## The rules\n\n")
	b.WriteString("| Rule | Applies to | Says |\n| --- | --- | --- |\n")
	for _, r := range denyRules {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.name, describeRule(r.name), r.detail)
	}
	b.WriteString("\n")
	b.WriteString("Sensitive permissions — the ones blinding is about: ")
	for i, p := range auth.SensitivePermissions {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "`%s`", p)
	}
	b.WriteString(".\n")
	return b.String()
}

func shortScope(s Scope) string {
	switch s {
	case ScopeOwnStation:
		return "station"
	case ScopeOwn:
		return "own"
	default:
		return "any"
	}
}

func describeRule(name string) string {
	switch name {
	case "nutritionist_no_prescriptions":
		return "NUTRITIONIST, every `prescription.*`"
	case "pharmacist_no_diagnoses":
		return "PHARMACIST, every `diagnosis.*` and every sensitive permission"
	case "registration_blinded":
		return "REGISTRATION, every sensitive permission"
	case "blinded_role_sensitive_resource":
		return "REGISTRATION and PHARMACIST, any read of a resource carrying a diagnosis"
	case "field_worker_no_facility_records":
		return "FIELD_WORKER, every `records.*` and `diagnosis.*`"
	default:
		return name
	}
}
