#!/usr/bin/env python3
"""Regenerate scripts/install-ci-files.ps1 from the files it installs.

The desktop file bridge refuses to write a Makefile or anything under .github/, so those
files are carried to a developer's machine as literal text inside a PowerShell script.
That arrangement has one obvious failure mode: the script falls behind the repository,
and the CI a developer installs is not the CI the repository describes.

So the script is generated rather than edited. Run this after changing the Makefile or
anything under .github/, and commit both. CI runs it too and fails on any difference, so
the two cannot drift apart quietly.

    python scripts/generate-install-ci-files.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "scripts" / "install-ci-files.ps1"

HEADER = """<#
.SYNOPSIS
  Write the build and CI files that cannot be transferred by the remote file bridge.
.DESCRIPTION
  The desktop bridge refuses to write Makefiles and anything under .github/ - a sensible
  guard, since those files control what runs on your machine and in CI. They are therefore
  embedded here as literal text and written locally by you.

  Generated by scripts/generate-install-ci-files.py. Do not edit by hand: edit the real
  file and regenerate, or your change will be overwritten and CI will fail on the diff.

  Safe to re-run. Existing files are overwritten only with -Force.
.EXAMPLE
  .\\scripts\\install-ci-files.ps1
  .\\scripts\\install-ci-files.ps1 -Force
#>
param([switch]$Force)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$written = 0
$skipped = 0

function Write-RepoFile {
    param([string]$RelativePath, [string]$Content)

    $full = Join-Path $repoRoot $RelativePath
    $dir = Split-Path -Parent $full
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }

    if ((Test-Path $full) -and -not $Force) {
        Write-Host ("  skip   $RelativePath (already exists; use -Force to overwrite)") -ForegroundColor Yellow
        $script:skipped++
        return
    }

    # Normalise to LF. Makefile recipes and shell scripts in CI break on CRLF.
    $normalised = $Content -replace "`r`n", "`n"

    # A PowerShell here-string discards the newline immediately before its terminator,
    # so restore it. Prettier, POSIX and every diff tool expect a trailing newline.
    if (-not $normalised.EndsWith("`n")) { $normalised += "`n" }
    [System.IO.File]::WriteAllText($full, $normalised, $utf8NoBom)
    Write-Host ("  write  $RelativePath") -ForegroundColor Green
    $script:written++
}

Write-Host ''
Write-Host 'Installing build and CI files' -ForegroundColor Cyan
Write-Host '-----------------------------'
"""

FOOTER = """
Write-Host ''
Write-Host ("Done: $written written, $skipped skipped.") -ForegroundColor Cyan
if ($skipped -gt 0) {
    Write-Host 'Re-run with -Force to overwrite the skipped files.'
}
Write-Host ''
"""


def files_to_embed() -> list[Path]:
    """The Makefile, then everything under .github/, in a stable order."""
    paths = [REPO / "Makefile"]
    github = REPO / ".github"
    if github.is_dir():
        paths += sorted(p for p in github.rglob("*") if p.is_file())
    return [p for p in paths if p.is_file()]


def variable_name(relative: str) -> str:
    safe = "".join(c if c.isalnum() else "_" for c in relative)
    return f"$content_{safe}"


def build() -> str:
    parts = [HEADER]

    for path in files_to_embed():
        relative = path.relative_to(REPO).as_posix()
        text = path.read_text(encoding="utf-8")

        # A single-quoted here-string ends at a line that begins with '@. Nothing in these
        # files does, but a silent truncation would be a very bad way to find out.
        if any(line.startswith("'@") for line in text.splitlines()):
            sys.exit(f"{relative} contains a line starting with '@, which would end the here-string early.")

        name = variable_name(relative)
        windows_path = relative.replace("/", "\\")
        parts.append(f"\n{name} = @'\n{text.rstrip(chr(10))}\n'@\n")
        parts.append(f"\nWrite-RepoFile -RelativePath '{windows_path}' -Content {name}\n")

    parts.append(FOOTER)
    return "".join(parts)


def main() -> int:
    generated = build()

    # A UTF-8 BOM, deliberately. Windows PowerShell 5.1 reads a BOM-less file as CP1252,
    # which turns any character above ASCII into mojibake and can terminate a string
    # early. That cost a whole debugging session at CP07.
    existing = TARGET.read_text(encoding="utf-8-sig") if TARGET.exists() else None

    if "--check" in sys.argv:
        if existing != generated:
            print("scripts/install-ci-files.ps1 is out of date.")
            print("Run: python scripts/generate-install-ci-files.py")
            return 1
        print("scripts/install-ci-files.ps1 is up to date.")
        return 0

    TARGET.write_text(generated, encoding="utf-8-sig", newline="\n")
    print(f"Wrote {TARGET.relative_to(REPO)} ({len(files_to_embed())} files embedded).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
