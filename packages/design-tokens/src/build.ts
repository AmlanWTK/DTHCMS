/**
 * Writes every artefact into `dist/` and returns the file names it wrote.
 *
 * This module only defines the build; `build.cli.ts` is what runs it. Keeping the two
 * apart means `build.test.ts` can import and call this directly instead of spawning
 * `npx tsx src/build.ts` — which worked on Linux and failed on Windows, where npx is
 * npx.cmd and `execFileSync` without a shell will not resolve a `.cmd`.
 *
 * A main-module check (`process.argv[1] === this file`) would also have worked, but its
 * failure mode on a path-casing difference is a build that silently writes nothing. A
 * separate entry file cannot fail that way.
 *
 * `report` exists so the CLI prints what it wrote and the test does not.
 */
export function build(report: (line: string) => void = () => {}): string[] {
  mkdirSync(dist, { recursive: true });

  const outputs: Array<[string, string]> = [
    ['tokens.css', buildCss()],
    ['tokens.print.css', buildPrintCss()],
    ['tailwind-theme.js', buildThemeModule('tailwind')],
    ['nativewind-theme.js', buildThemeModule('nativewind')],
    [
      'tokens.json',
      `${JSON.stringify({ ramps, themes, clinicalStatuses, layout: layout.size }, null, 2)}\n`,
    ],
  ];

  for (const [name, contents] of outputs) {
    writeFileSync(join(dist, name), contents, 'utf8');
    report(`  ${name}  ${contents.length.toLocaleString()} bytes`);
  }

  return outputs.map(([name]) => name);
}
